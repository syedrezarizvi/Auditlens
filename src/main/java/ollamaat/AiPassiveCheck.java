package ollamaat;

import burp.api.montoya.http.message.HttpRequestResponse;
import burp.api.montoya.scanner.AuditResult;
import burp.api.montoya.scanner.ConsolidationAction;
import burp.api.montoya.scanner.audit.issues.AuditIssue;
import burp.api.montoya.scanner.audit.issues.AuditIssueConfidence;
import burp.api.montoya.scanner.audit.issues.AuditIssueSeverity;
import burp.api.montoya.scanner.scancheck.PassiveScanCheck;
import ollamaat.agent.Memory;
import ollamaat.llm.OllamaClient;
import ollamaat.tools.Fmt;
import ollamaat.util.Json;
import ollamaat.util.Text;

import java.util.*;
import java.util.concurrent.Semaphore;
import java.util.concurrent.TimeUnit;

/** Optional passive scan check: asks the local model to review in-scope responses. Off by default, deduplicated, serialised. */
public final class AiPassiveCheck implements PassiveScanCheck {
    private static final Set<String> SKIP_TYPES = Set.of("image", "font", "video", "audio");
    private final Engine engine;
    private final PassiveReviewer reviewer;
    private final Semaphore gate = new Semaphore(1);
    private final Set<String> seen = Collections.newSetFromMap(new java.util.concurrent.ConcurrentHashMap<>());
    /** How long a request waits for the model to finish the previous review before it is skipped. */
    private static final int WAIT_SECONDS = 300;

    public AiPassiveCheck(Engine engine) { this.engine = engine; this.reviewer = new PassiveReviewer(engine); }

    @Override public String checkName() { return "AuditLens AI passive review"; }

    @Override
    public AuditResult doCheck(HttpRequestResponse rr) {
        Settings s = engine.settings;
        if (!s.aiPassiveScan() || s.model().isBlank() || !rr.hasResponse()) return AuditResult.auditResult(List.of());
        if (!engine.api.scope().isInScope(rr.request().url())) return AuditResult.auditResult(List.of());
        String ct = Fmt.contentType(rr.response());
        for (String t : SKIP_TYPES) if (ct.startsWith(t)) return AuditResult.auditResult(List.of());
        String key = rr.request().method() + " " + rr.httpService().host() + Text.pathTemplate(rr.request().path()) + " " + rr.response().statusCode() + " " + ct;
        if (!seen.add(key)) return AuditResult.auditResult(List.of());
        boolean got = false;
        try {
            got = gate.tryAcquire(WAIT_SECONDS, TimeUnit.SECONDS);
            if (!got) {
                // Previously dropped silently. Forget the key so the same endpoint can be reviewed on a later pass.
                seen.remove(key);
                engine.api.logging().logToOutput("AuditLens passive check: skipped " + rr.request().url()
                        + " (model still busy after " + WAIT_SECONDS + "s; use a faster/smaller model or fewer requests)");
                return AuditResult.auditResult(List.of());
            }
            engine.api.logging().logToOutput("AuditLens passive check: reviewing " + rr.request().method() + " " + rr.request().url());
            List<AuditIssue> issues = review(rr);
            engine.api.logging().logToOutput("AuditLens passive check: " + issues.size() + " issue(s) for " + rr.request().url());
            return AuditResult.auditResult(issues);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            return AuditResult.auditResult(List.of());
        } catch (Exception e) {
            seen.remove(key); // allow a retry once the problem (e.g. Ollama not running) is fixed
            engine.api.logging().logToError("AuditLens passive check failed for " + rr.request().url() + ": " + e);
            return AuditResult.auditResult(List.of());
        } finally {
            if (got) gate.release();
        }
    }

    private List<AuditIssue> review(HttpRequestResponse rr) throws Exception {
        List<AuditIssue> out = new ArrayList<>();
        for (PassiveReviewer.Obs o : reviewer.review(rr)) {
            AuditIssueSeverity sev = switch (o.severity()) {
                case "high" -> AuditIssueSeverity.HIGH;
                case "medium" -> AuditIssueSeverity.MEDIUM;
                case "low" -> AuditIssueSeverity.LOW;
                default -> AuditIssueSeverity.INFORMATION;
            };
            String detail = "<p>" + esc(o.detail()) + "</p><p><b>Evidence:</b> " + esc(o.evidence()) + "</p>";
            out.add(AuditIssue.auditIssue("[AI] " + o.name(), detail, null, rr.request().url(), sev, AuditIssueConfidence.TENTATIVE,
                    "<p>Generated by a local LLM via AuditLens passive review. Tentative: verify manually.</p>", null, sev, rr));
            // Also record in AuditLens's Findings tab (duplicate-safe), so findings appear there and in the HTML report.
            try {
                if (!engine.memory.hasFinding(o.name(), rr.request().url())) {
                    String ref = engine.evidence.addSelected(rr);
                    String plain = o.detail() + (o.evidence().isBlank() ? "" : "\nEvidence: " + o.evidence());
                    engine.memory.addFindingIfAbsent(new Memory.Finding(System.currentTimeMillis(), 0, o.name(), sev.name(),
                            AuditIssueConfidence.TENTATIVE.name(), rr.request().url(), plain, "", List.of(ref), true));
                }
            } catch (RuntimeException e) {
                engine.api.logging().logToError("AuditLens passive check: could not record finding: " + e);
            }
        }
        return out;
    }

    private static String esc(String s) { return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"); }

    @Override
    public ConsolidationAction consolidateIssues(AuditIssue existing, AuditIssue added) {
        return existing.name().equals(added.name()) && existing.baseUrl().equals(added.baseUrl())
                ? ConsolidationAction.KEEP_EXISTING : ConsolidationAction.KEEP_BOTH;
    }
}
